class StreamChunk:
    """Represents a chunk emitted during streaming generation.

    Attributes:
        text (Optional[str]): The generated text content chunk.
        thought (Optional[str]): The generated thinking/reasoning chunk.
        thought_signature (Optional[str]): Reasoning signature for this chunk or tool call.
        tool_calls (Optional[List[ToolCall]]): Any tool calls in this chunk.
        usage (Optional[UsageStats]): Token usage statistics if emitted.
        finish_reason (Optional[str]): Finish reason if emitted in chunk.
        safety_ratings (Optional[List[SafetyRating]]): Safety ratings if present.
        citations (Optional[List[Citation]]): Citations if present.
        model_version (Optional[str]): Model version if present.
        response_id (Optional[str]): Response ID if present.
    """

    text: str | None = None
    thought: str | None = None
    thought_signature: str | None = None
    tool_calls: list[ToolCall] | None = None
    usage: UsageStats | None = None
    finish_reason: str | None = None
    safety_ratings: list[SafetyRating] | None = None
    citations: list[Citation] | None = None
    model_version: str | None = None
    response_id: str | None = None

    @property
    def is_thought(self) -> bool:
        return self.thought is not None

    @property
    def is_text(self) -> bool:
        return self.text is not None

    @property
    def is_tool_call(self) -> bool:
        return self.tool_calls is not None

    def __str__(self) -> str:
        if self.text is not None:
            return self.text
        if self.thought is not None:
            return self.thought
