@dataclass
class FileAttachment:
    """Represents a file attachment to be sent with a message or generated by the model.

    Attributes:
        mime_type (str): The MIME type of the file (e.g., 'image/png').
        data (str): The base64-encoded string of the file's content.
    """

    mime_type: str
    data: str

    @classmethod
    def from_file(cls, file_path: str, mime_type: str | None = None) -> FileAttachment:
        """Creates a FileAttachment by reading a local file.

        Args:
            file_path (str): Path to the local file.
            mime_type (Optional[str]): Explicit MIME type. If None, guessed from file extension.

        Returns:
            FileAttachment: Initialized instance with base64 encoded content.
        """
        if not mime_type:
            guessed_type, _ = mimetypes.guess_type(file_path)
            mime_type = guessed_type or "application/octet-stream"
        with open(file_path, "rb") as f:
            encoded = base64.b64encode(f.read()).decode("utf-8")
        return cls(mime_type=mime_type, data=encoded)

    @classmethod
    def from_bytes(cls, raw_bytes: bytes, mime_type: str = "image/png") -> FileAttachment:
        """Creates a FileAttachment directly from raw bytes.

        Args:
            raw_bytes (bytes): Raw binary data.
            mime_type (str): MIME type of the data (default: 'image/png').

        Returns:
            FileAttachment: Initialized instance with base64 encoded content.
        """
        encoded = base64.b64encode(raw_bytes).decode("utf-8")
        return cls(mime_type=mime_type, data=encoded)

    def to_bytes(self, validate: bool = True) -> bytes:
        """Decodes the base64 data into raw bytes.

        Args:
            validate (bool): If True, strictly validates that the string contains valid base64 data.

        Returns:
            bytes: The binary representation of the attachment.
        """
        return base64.b64decode(self.data, validate=validate)

    def save(self, file_path: str) -> None:
        """Saves the attachment directly to a file on disk.

        Args:
            file_path (str): Destination file path.
        """
        parent_dir = os.path.dirname(file_path)
        if parent_dir:
            os.makedirs(parent_dir, exist_ok=True)
        with open(file_path, "wb") as f:
            f.write(self.to_bytes())


