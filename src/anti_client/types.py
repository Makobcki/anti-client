@dataclass
class CountTokensResult:
    """Result from the countTokens endpoint."""

    total_tokens: int

    def __int__(self) -> int:
        return self.total_tokens

    def __index__(self) -> int:
        return self.total_tokens

    def __repr__(self) -> str:
        return f"CountTokensResult(total_tokens={self.total_tokens})"

    def __eq__(self, other: object) -> bool:
        if isinstance(other, int):
            return self.total_tokens == other
        if isinstance(other, CountTokensResult):
            return self.total_tokens == other.total_tokens
        return False

    def __lt__(self, other: Any) -> bool:
        if isinstance(other, (int, CountTokensResult)):
            return self.total_tokens < int(other)
        return NotImplemented

    def __le__(self, other: Any) -> bool:
        if isinstance(other, (int, CountTokensResult)):
            return self.total_tokens <= int(other)
        return NotImplemented

    def __gt__(self, other: Any) -> bool:
        if isinstance(other, (int, CountTokensResult)):
            return self.total_tokens > int(other)
        return NotImplemented

    def __ge__(self, other: Any) -> bool:
        if isinstance(other, (int, CountTokensResult)):
            return self.total_tokens >= int(other)
        return NotImplemented

    def __add__(self, other: Any) -> int:
        if isinstance(other, (int, CountTokensResult)):
            return self.total_tokens + int(other)
        return NotImplemented

    def __radd__(self, other: Any) -> int:
        if isinstance(other, (int, CountTokensResult)):
            return int(other) + self.total_tokens
        return NotImplemented

    def __sub__(self, other: Any) -> int:
        if isinstance(other, (int, CountTokensResult)):
            return self.total_tokens - int(other)
        return NotImplemented
