@dataclass
class ModelsCatalog:
    """Catalog of available models and specialized category listings.

    Attributes:
        models (List[ModelInfo]): All discovered model definitions.
        default_agent_model_id (str): Recommended default agent model ID.
        agent_model_sorts (List[str]): Preferred sort order of agent model IDs.
        deprecated_model_ids (List[str]): List of deprecated model IDs.
        deprecated_model_map (Dict[str, str]): Mapping of deprecated model IDs to recommended alternatives.
        web_search_model_ids (List[str]): Models supporting web search grounding.
        image_generation_model_ids (List[str]): Models supporting image generation.
        command_model_ids (List[str]): Models optimized for command execution.
        mquery_model_ids (List[str]): Models for multi-query execution.
        commit_message_model_ids (List[str]): Models for commit message generation.
        audio_transcription_model_ids (List[str]): Models for audio transcription.
        tab_model_ids (List[str]): Models for code completion/tab suggestions.
        tiered_model_ids (Optional[Dict[str, List[str]]]): Groupings of tiered model IDs.
    """

    models: list[ModelInfo]
    default_agent_model_id: str = "gemini-3.1-pro-low"
    agent_model_sorts: list[str] = field(default_factory=list)
    deprecated_model_ids: list[str] = field(default_factory=list)
    deprecated_model_map: dict[str, str] = field(default_factory=dict)
    web_search_model_ids: list[str] = field(default_factory=list)
    image_generation_model_ids: list[str] = field(default_factory=list)
    command_model_ids: list[str] = field(default_factory=list)
    mquery_model_ids: list[str] = field(default_factory=list)
    commit_message_model_ids: list[str] = field(default_factory=list)
    audio_transcription_model_ids: list[str] = field(default_factory=list)
    tab_model_ids: list[str] = field(default_factory=list)
    tiered_model_ids: dict[str, list[str]] | None = None

    def get_model(self, model_id: str) -> ModelInfo | None:
        """Finds a model by its ID or internal model ID."""
        for m in self.models:
            if m.id == model_id or m.internal_model_id == model_id:
                return m
        return None


@dataclass
class QuotaBucket:
    """Individual quota bucket for a specific window."""

    bucket_id: str
    display_name: str
    window: str  # "weekly" | "5h"
    reset_time: str
    description: str
    remaining_fraction: float


@dataclass
class QuotaGroup:
    """Group of quota buckets sharing limits (e.g. Gemini Models, Claude and GPT)."""

    display_name: str
    description: str
    buckets: list[QuotaBucket] = field(default_factory=list)

    @property
    def weekly(self) -> QuotaBucket | None:
        """Returns the weekly limit quota bucket if present."""
        return next(
            (b for b in self.buckets if b.window == "weekly" or "weekly" in b.bucket_id.lower()),
            None,
        )

    @property
    def five_hour(self) -> QuotaBucket | None:
        """Returns the 5-hour limit quota bucket if present."""
        return next(
            (b for b in self.buckets if b.window == "5h" or "5h" in b.bucket_id.lower()),
            None,
        )


@dataclass
class QuotaSummary:
    """Summary of user quota status across model families."""

    groups: list[QuotaGroup] = field(default_factory=list)
    description: str = ""

    @property
    def gemini(self) -> QuotaGroup | None:
        """Returns quota group for Gemini models."""
        return next(
            (g for g in self.groups if "gemini" in g.display_name.lower()),
            None,
        )

    @property
    def claude(self) -> QuotaGroup | None:
        """Returns quota group for Claude and 3P models."""
        return next(
            (
                g
                for g in self.groups
                if any(
                    k in g.display_name.lower()
                    for k in ("claude", "gpt", "3p", "anthropic", "openai")
                )
            ),
            None,
        )


